#!/usr/bin/env node
// install-skills.mjs
//
// Registers the canonical skills in `.agents/skills/` in the native skills
// folder of one or more harnesses, so they show up as slash commands / skills.
//
// It does NOT copy the playbooks: for each skill it writes a thin wrapper
// SKILL.md (same `name` + `description`) whose body points back to the
// canonical file. That way there is a single source of truth and nothing drifts.
//
// Usage:
//   node scripts/install-skills.mjs claude codex
//   node scripts/install-skills.mjs path/to/custom/skills-dir
//
// Known harness names map to their project-level skills folder. Folder
// conventions change between versions: if your harness reads skills from a
// different place, pass that folder as a path instead.
//
// No dependencies. Works on Windows, macOS and Linux with any Node >= 18.

import { readFileSync, readdirSync, mkdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = join(ROOT, '.agents', 'skills');

const HARNESS_DIRS = {
  claude: '.claude/skills',
  codex: '.codex/skills',
  gemini: '.gemini/skills',
  cursor: '.cursor/skills',
  opencode: '.opencode/skills',
};

function readFrontmatter(text) {
  const match = text.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!match) return {};
  const fields = {};
  for (const line of match[1].split(/\r?\n/)) {
    const kv = line.match(/^([A-Za-z_][\w-]*):\s*(.*)$/);
    if (kv) fields[kv[1]] = kv[2].trim();
  }
  return fields;
}

function wrapper(name, description, canonicalPath) {
  return [
    '---',
    `name: ${name}`,
    `description: ${description}`,
    '---',
    '',
    `# Skill: ${name}`,
    '',
    `This is a thin adapter generated by \`scripts/install-skills.mjs\`. The canonical playbook is **\`${canonicalPath}\`**.`,
    '',
    `Read \`${canonicalPath}\` now and follow it step by step, together with the general rules in \`AGENTS.md\`. Do not edit this file — edit the canonical one and re-run the script if the name or description change.`,
    '',
  ].join('\n');
}

function main() {
  const targets = process.argv.slice(2);
  if (targets.length === 0) {
    console.error(
      `Usage: node scripts/install-skills.mjs <${Object.keys(HARNESS_DIRS).join('|')}|path> [...]`
    );
    process.exit(1);
  }

  const skills = readdirSync(SOURCE, { withFileTypes: true })
    .filter((d) => d.isDirectory() && existsSync(join(SOURCE, d.name, 'SKILL.md')))
    .map((d) => d.name);

  for (const target of targets) {
    const destRoot = resolve(ROOT, HARNESS_DIRS[target] ?? target);
    for (const skill of skills) {
      const fm = readFrontmatter(readFileSync(join(SOURCE, skill, 'SKILL.md'), 'utf8'));
      const name = fm.name || skill;
      const canonical = relative(ROOT, join(SOURCE, skill, 'SKILL.md')).split('\\').join('/');
      const destDir = join(destRoot, skill);
      mkdirSync(destDir, { recursive: true });
      writeFileSync(join(destDir, 'SKILL.md'), wrapper(name, fm.description || '', canonical));
    }
    console.log(`✅ ${skills.length} skills registered in ${relative(ROOT, destRoot) || '.'}`);
  }
}

main();
